import { readFile } from 'node:fs/promises'
import { describe, expect, it } from 'vitest'

describe('ThreadSubagentPanel desktop sidebar wiring', () => {
  it('merges live content by ID only when the selected history window reaches the latest turn', async () => {
    const source = await readFile(new URL('./ThreadSubagentPanel.vue', import.meta.url), 'utf8')
    const app = await readFile(new URL('../../App.vue', import.meta.url), 'utf8')
    expect(source).toContain(':messages="selectedMessages"')
    expect(source).toContain('if (detail.hasMoreNewer || !selectedAgent.value) return detail.messages')
    expect(source).toContain('selectedAgent.value && !selectedDetail.value?.hasMoreNewer')
    expect(source).toContain('props.liveMessagesForThread(selectedAgent.value.threadId)')
    expect(source).toContain('mergeCurrentSubagentMessages(detail.messages, live)')
    expect(app).toContain(':live-messages-for-thread="getCurrentTurnMessagesForThread"')
    expect(app).toContain(':prepare-snapshot-for-thread="prepareSubagentSnapshot"')
    expect(source).toContain('useThreadHistoryWindow(selectedThreadId, props.prepareSnapshotForThread)')
  })
  it('keeps the desktop agent sidebar resizable, collapsible, and persisted', async () => {
    const source = await readFile(new URL('./ThreadSubagentPanel.vue', import.meta.url), 'utf8')

    expect(source).toContain('class="subagent-panel-host"')
    expect(source).toContain('class="subagent-panel-resizer"')
    expect(source).toContain('role="separator"')
    expect(source).toContain('aria-orientation="vertical"')
    expect(source).toContain('tabindex="0"')
    expect(source).toContain(':aria-valuemin="MIN_DESKTOP_PANEL_WIDTH"')
    expect(source).toContain(':aria-valuemax="desktopPanelMaximum"')
    expect(source).toContain(':aria-valuenow="desktopPanelRenderedWidth"')
    expect(source).toContain('@pointerdown="onDesktopResizePointerDown"')
    expect(source).toContain('@keydown="onDesktopResizerKeyDown"')
    expect(source).toContain("codex-web-local.subagent-panel-width.v1")
    expect(source).toContain("codex-web-local.subagent-panel-collapsed.v1")
    expect(source).toContain('setPointerCapture(event.pointerId)')
    expect(source).toContain("addEventListener('lostpointercapture', onDesktopResizePointerCaptureLost)")
    expect(source).toContain("window.addEventListener('blur', onDesktopResizeWindowBlur)")
    expect(source).toContain("window.removeEventListener('pointercancel', onDesktopResizePointerEnd)")
    expect(source).toContain('new ResizeObserver(onDesktopLayoutResize)')
    expect(source).toContain('desktopLayoutResizeObserver?.disconnect()')
    expect(source).toContain('class="subagent-desktop-toolbar"')
    expect(source).toContain('v-show="isMobile || desktopPanelExpanded"')
    expect(source).toContain('canExpandDesktopPanel(desktopLayoutWidth.value)')
    expect(source).not.toContain(':disabled="!desktopPanelCanExpand"')
    expect(source).toContain("emit('request-desktop-expand')")
    expect(source).toContain("emit('desktop-expanded-change', expanded)")
    expect(source).toContain('defineExpose({ collapseDesktopPanel })')
    expect(source).toContain("host?.closest<HTMLElement>('.content-root')")
    expect(source).toContain('watch(() => [desktopHostRef.value, isMobile.value, mobileSheetOpen.value]')
    expect(source).not.toContain('margin-left: -0.75rem')
    expect(source).not.toContain('min-width: 17.5rem')
    expect(source).not.toContain('subagent-panel-footer')
    expect(source).toContain('@click="toggleSubagentPanel"')
    expect(source).toContain('if (desktopPanelCollapsed.value === opening) toggleDesktopPanel()')
    const toggleBody = source.match(/function toggleDesktopPanel\(\): void \{([\s\S]*?)\n\}/u)?.[1] ?? ''
    expect(toggleBody).not.toContain('getThreadDetail')
    expect(source).not.toMatch(/<aside\s+v-if=/u)
  })

  it('keeps mobile sheet behavior separate and allows desktop details to shrink', async () => {
    const source = await readFile(new URL('./ThreadSubagentPanel.vue', import.meta.url), 'utf8')

    expect(source).toContain('const activeAgents = computed')
    const appSource = await readFile(new URL('../../App.vue', import.meta.url), 'utf8')

    expect(source).toContain('v-if="parentThreadId && !mobileSheetOpen"')
    expect(source).toContain('v-for="(agent, index) in visibleAgents"')
    expect(source).toContain('if (!allAgents.value.some((agent) => agent.threadId === threadId)) return')
    expect(source).toMatch(/watch\(\s*allAgents,[\s\S]*closeDetail\(\)/u)
    expect(source).toContain('const selectedAgent = computed(() => allAgents.value.find(')
    expect(source).toContain('getThreadCollaborationPage(props.parentThreadId, historyCursor.value)')
    expect(source).toContain('!loadingOlder.value && !loadingNewer.value && !agentWindowLoading.value')
    expect(source).toContain('useThreadHistoryWindow(selectedThreadId, props.prepareSnapshotForThread)')
    expect(source).not.toContain('void selectAgent(threadId)')
    expect(source).toContain('<Teleport v-if="isMobile || !desktopPanelExpanded" to="#thread-subagent-header-target">')
    expect(source).toContain('class="subagent-header-trigger"')
    expect(appSource).toContain('id="thread-subagent-header-target"')
    expect(source).toContain('<Teleport to="body" :disabled="!isMobile || !mobileSheetOpen">')
    expect(source).toContain(':is-history-window="selectedDetail.hasMoreNewer === true"')
    expect(source).toMatch(/watch\(\(\) => props.parentThreadId,[\s\S]*mobileSheetOpen.value = false/u)
    expect(source).toContain('.subagent-panel.is-mobile-open')
    expect(source).toContain('@media (max-width: 767px)')
    expect(source).toMatch(/\.subagent-panel-surface\s*\{[\s\S]*min-w-0[\s\S]*w-full/u)
    expect(source).toMatch(/@media \(max-width: 767px\)[\s\S]*\.subagent-panel-host\s*\{[\s\S]*display:\s*contents/u)
    const styles = await readFile(new URL('../../style.css', import.meta.url), 'utf8')
    expect(styles).toContain(':root.dark .subagent-panel,')
    expect(styles).toContain(':root.dark .subagent-panel.is-mobile-open .subagent-panel-surface')
  })

  it('releases the collapsed desktop column while preserving the selected conversation and header control', async () => {
    const source = await readFile(new URL('./ThreadSubagentPanel.vue', import.meta.url), 'utf8')
    const app = await readFile(new URL('../../App.vue', import.meta.url), 'utf8')
    expect(source).toMatch(/<div\s+v-if="parentThreadId[^"\n]*"\s+v-show="isMobile \|\| desktopPanelExpanded"/u)
    expect(app).toContain('<span id="thread-subagent-header-target" class="content-header-subagent-target" />')
    expect(source).toContain('ref="headerTriggerRef"')
    expect(source).toContain('ref="desktopTriggerRef"')
    expect(source).toContain('trigger?.focus({ preventScroll: true })')
    const toggle = source.match(/async function toggleSubagentPanel\(\): Promise<void> \{([\s\S]*?)\n\}/u)?.[1] ?? ''
    expect(toggle).not.toContain('closeDetail()')
    expect(toggle).not.toContain('loadAgentLatestMessages()')
  })
})
